# 阶段 → 优先业务域（按 round_no 轮换取子集，保证 12 题覆盖多个域）
STAGE_DOMAINS: dict[str, list[str]] = {
    "resume": ["plate_structure", "dealer_system", "sell_through", "team_kpi"],
    "professional": ["channel_mix", "model_mix", "inventory_cash", "pricing_promo",
                     "project_ka", "online_conflict", "policy_landing", "sell_through"],
    "pressure": ["inventory_cash", "project_ka", "online_conflict", "channel_governance"],
    "intro": ["plate_structure"],
    "ask": [],
}


def domains_for_stage(stage: str, round_no: int = 1, count: int = 4) -> list[dict[str, Any]]:
    """按阶段取业务域（轮换，保证不同题问不同域）。"""
    ids = STAGE_DOMAINS.get(stage) or []
    if not ids:
        return []
    start = max(0, (round_no - 1)) % len(ids)
    picked = [DOMAIN_BY_ID[ids[(start + i) % len(ids)]] for i in range(min(count, len(ids)))]
    return picked


def domains_text(stage: str, round_no: int, count: int = 4) -> str:
    """渲染成提示词块：本阶段该问的业务域 + 高手问题 + 套话对照。"""
    doms = domains_for_stage(stage, round_no, count)
    if not doms:
        return ""
    lines = ["【渠道操盘业务题库（本轮优先从这几个域提问，问题必须指向机制/算法/对价，禁止问「你怎么做的」这类空问）】"]
    for d in doms:
        lines.append(f"● {d['name']}——关注口径与指标：{d['metrics']}")
        for q in d["questions"]:
            lines.append(f"   · {q}")
        lines.append(f"   · 套话对照：{d['platitude']} → {d['concrete']}")
    return "\n".join(lines) + "\n"


