def analyze_answer(text: str) -> dict[str, Any]:
    """确定性分析一段回答的"业务含金量"：套话 vs 数字 vs 业务名词。"""
    t = text or ""
    strong = [(w, t.count(w), v) for w, v in PLATITUDE_STRONG.items() if w in t]
    weak = [(w, t.count(w), v) for w, v in PLATITUDE_WEAK.items() if w in t]
    strong_hits = sum(c for _, c, _ in strong)
    weak_hits = sum(c for _, c, _ in weak)
    platitude_score = sum(c * v for _, c, v in strong) + sum(c * v for _, c, v in weak) * 0.5
    nums = _NUM_RE.findall(t)
    units = _UNIT_RE.findall(t)
    terms = [w for w in BUSINESS_TERMS if w in t]
    chars = len(re.sub(r"\s", "", t))

    if chars < 20:
        verdict = "过短"
    elif platitude_score >= 4 and len(nums) <= 1:
        verdict = "套话为主"
    elif len(nums) >= 3 and len(terms) >= 4:
        verdict = "具体"
    elif len(nums) >= 1 and len(terms) >= 2:
        verdict = "偏泛"
    else:
        verdict = "缺业务细节"

    missing: list[str] = []
    if len(nums) < 2:
        missing.append("缺数字（量级/占比/周期）")
    if not re.search(r"(回款|出货|零售|GMV)", t):
        missing.append("缺口径（出货/回款/零售）")
    if not re.search(r"(返利|账期|授信|控价|窜货)", t):
        missing.append("缺机制（返利/账期/控价）")
    if not re.search(r"(毛利|费用率|ROI|折让|回本|盈利)", t):
        missing.append("缺对价（毛利/费用/折让/回本）")
    if not re.search(r"(台账|流程|标准|SOP|步骤|节奏)", t):
        missing.append("缺可复制性（步骤/标准/节奏）")

    return {
        "chars": chars,
        "digits": len(nums),
        "units": len(units),
        "business_terms": terms,
        "platitude_hits": [{"term": w, "count": c} for w, c, _ in sorted(strong + weak, key=lambda x: -x[2])],
        "platitude_score": round(platitude_score, 1),
        "verdict": verdict,
        "missing": missing,
    }


def analyze_text(text: str) -> str:
    """渲染成提示词块（注入面试官与复盘，让他们有据可依地戳套话）。"""
    a = analyze_answer(text)
    if a["chars"] == 0:
        return ""
    hits = "、".join(f"{h['term']}×{h['count']}" for h in a["platitude_hits"][:8]) or "无"
    terms = "、".join(a["business_terms"][:12]) or "无"
    return (
        "【本地业务含金量检测（确定性统计，供你判断这次回答虚实）】\n"
        f"- 判定：**{a['verdict']}** ｜ 字数 {a['chars']} ｜ 数字 {a['digits']} 个 ｜ 业务名词 {len(a['business_terms'])} 个\n"
        f"- 套话命中：{hits}（套话分 {a['platitude_score']}）\n"
        f"- 已出现的业务名词：{terms}\n"
        + (f"- 明显缺失：{'；'.join(a['missing'])}\n" if a["missing"] else "")
        + "使用要求：若判定为「套话为主」或「缺业务细节」，**本轮必须用业务机制问题追问**"
        "（口径/结构/算法/对价四类），并可直接引用上面缺失的维度；不得因为对方用了业务术语就放过。\n"
    )


