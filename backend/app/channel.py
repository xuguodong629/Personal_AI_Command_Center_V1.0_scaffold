def followups_for(domain_id: str, count: int = 3) -> list[str]:
    """按业务域给出可用追问句（供提示词参考，避免面试官只会问"还有呢"）。"""
    d = DOMAIN_BY_ID.get(domain_id)
    out: list[str] = []
    if d:
        out += d["questions"][:count]
    return out or [q for group in FOLLOWUP_TEMPLATES.values() for q in group][:count]


def all_followups_text() -> str:
    lines = ["【追问模板（按需选用，避免只会问「还有呢」）】"]
    for k, qs in FOLLOWUP_TEMPLATES.items():
        lines.append(f"● {k}：" + " ｜ ".join(qs))
    return "\n".join(lines) + "\n"
