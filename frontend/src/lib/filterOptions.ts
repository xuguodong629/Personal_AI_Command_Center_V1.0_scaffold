/**
 * 筛选选项库（照搬招聘网站分类逻辑）
 * - 区域：全国范围 / 直辖市 / 各省地级市（覆盖全国）
 * - 行业：按大类分组的全行业门类
 * - 岗位：按职类分组的全岗位职类
 * 所有字段均支持手动输入自定义项。
 */

const flat = (map: Record<string, string[]>): MSOption[] =>
  Object.entries(map).flatMap(([group, items]) => items.map(v => ({ value: v, label: v, group })));

const dedupe = (list: MSOption[]): MSOption[] => {
  const seen = new Set<string>();
  return list.filter(o => (seen.has(o.value) ? false : (seen.add(o.value), true)));
};

